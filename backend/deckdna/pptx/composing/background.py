"""Slide-local artwork survives content recomposition as editable layers."""

from __future__ import annotations

import copy

from lxml import etree

from deckdna.pptx.composing.artwork import covers_canvas
from deckdna.pptx.composing.chart_colors import chart_colors
from deckdna.pptx.composing.table_fill import _el_box, _next_shape_id

A = "http://schemas.openxmlformats.org/drawingml/2006/main"
P = "http://schemas.openxmlformats.org/presentationml/2006/main"


def background_layers(root: etree._Element, width: int, height: int) -> list[etree._Element]:
    """Textless, filled artwork covering the canvas, in its original z-order."""
    tree = root.find(f"{{{P}}}cSld/{{{P}}}spTree")
    if tree is None or width <= 0 or height <= 0:
        return []
    layers = []
    for element in tree:
        tag = etree.QName(element).localname
        if tag not in {"sp", "grpSp", "pic"}:
            continue
        if any((t.text or "").strip() for t in element.iter(f"{{{A}}}t")):
            continue
        if (
            tag != "pic"
            and next(
                element.iter(
                    *(
                        f"{{{A}}}{fill}"
                        for fill in ("solidFill", "gradFill", "pattFill", "blipFill")
                    )
                ),
                None,
            )
            is None
        ):
            continue
        box = _el_box(element)
        if box is None:
            continue
        x, y, w, h = box
        if covers_canvas(x, y, w, h, width, height):
            layers.append(element)
    return layers


def restore_background_layers(
    source_xml: bytes, slide_xml: bytes, width: int, height: int
) -> bytes:
    """Restore artwork removed with donor text by a fallback composition.

    The output slide is cloned from the same donor, so its relationship IDs
    stay valid. New shape IDs avoid collisions with newly composed content.
    Only panels generated by our fallback are removed from above the artwork.
    """
    layers = background_layers(etree.fromstring(source_xml), width, height)
    if not layers:
        return slide_xml
    root = etree.fromstring(slide_xml)
    tree = root.find(f"{{{P}}}cSld/{{{P}}}spTree")
    if tree is None:
        return slide_xml
    panels = {"DeckDNA visual panel", "DeckDNA bibliography panel", "DeckDNA heading backdrop"}
    for element in list(tree):
        props = element.find(f"./*/{{{P}}}cNvPr")
        if props is not None and props.get("name") in panels:
            tree.remove(element)
    existing = {etree.tostring(el) for el in tree}
    shape_id = _next_shape_id(root)
    for index, layer in enumerate(layers):
        if etree.tostring(layer) in existing:
            continue
        clone = copy.deepcopy(layer)
        for props in clone.iter(f"{{{P}}}cNvPr"):
            props.set("id", str(shape_id))
            shape_id += 1
        tree.insert(2 + index, clone)
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8")


def align_composed_text_ink(
    parts: dict[str, bytes], slide_part: str, slide_xml: bytes, source_xml: bytes | None = None
) -> bytes:
    """Choose generated text ink against the local panel, with theme resolution.

    In particular bg1 is not necessarily light and bg2 is not necessarily
    dark. Authored donor text remains styled by the donor.
    """
    root = etree.fromstring(slide_xml)
    parts = {**parts, slide_part: slide_xml}
    authored = set()
    if source_xml is not None:
        authored = {
            (el.get("id"), el.get("name"))
            for el in etree.fromstring(source_xml).iter(f"{{{P}}}cNvPr")
        }
    for shape in root.iter(f"{{{P}}}sp"):
        props = shape.find(f"{{{P}}}nvSpPr/{{{P}}}cNvPr")
        box = _el_box(shape)
        if props is None or box is None:
            continue
        generated = props.get("name", "").startswith("DeckDNA ") or (
            source_xml is not None and (props.get("id"), props.get("name")) not in authored
        )
        if not generated:
            continue
        ink = chart_colors(parts, slide_part, box).ink
        if ink is None:
            continue
        for run_props in shape.iter(f"{{{A}}}rPr", f"{{{A}}}defRPr", f"{{{A}}}endParaRPr"):
            for child in list(run_props):
                if etree.QName(child).localname in {
                    "solidFill",
                    "gradFill",
                    "noFill",
                    "pattFill",
                    "blipFill",
                }:
                    run_props.remove(child)
            fill = etree.Element(f"{{{A}}}solidFill")
            etree.SubElement(fill, f"{{{A}}}srgbClr", val=ink)
            run_props.insert(0, fill)
    return etree.tostring(root, xml_declaration=True, encoding="UTF-8")
